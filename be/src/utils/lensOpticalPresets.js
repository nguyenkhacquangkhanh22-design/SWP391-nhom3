function findLensPresetByTitle(title) {
  if (!title) return null;
  const t = title.toLowerCase();
  for (const preset of LENS_OPTICAL_PRESETS) {
    if (t.includes(preset.model.toLowerCase()) || (t.includes(preset.brand.toLowerCase()) && t.includes(String(preset.focal_length_tested_mm)))) {
      return preset;
    }
  }
  return null;
}

